export function adminText(locale: 'zh' | 'en', key: AdminMessage, params: Record<string, string | number> = {}) {
  const text = locale === 'zh' ? key : adminMessages[key]
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match))
}

export function adminLabel(locale: 'zh' | 'en', value: string) {
  if (Object.prototype.hasOwnProperty.call(labels, value)) return adminText(locale, labels[value])
  if (Object.prototype.hasOwnProperty.call(adminMessages, value)) return adminText(locale, value as AdminMessage)
  if (Object.prototype.hasOwnProperty.call(adminErrors, value)) return locale === 'zh' ? value : adminErrors[value]
  return value
}

export function adminError(locale: 'zh' | 'en', value: string) {
  const key = Object.prototype.hasOwnProperty.call(adminErrors, value) ? value : '連線失敗，請再試一次。'
  return locale === 'zh' ? key : adminErrors[key]
}
